static uint16_t readWord(const uint8_t *p) {
    return (uint16_t)(p[0] | (p[1] << 8));
}

// sub_7C3F : avance de cl bits dans le registre dx (dh = octet suivant, ch = bits encore dans dh).
static void consumeBits(uint16_t &dx, int &ch, int cl, const std::vector<uint8_t> &source, size_t &di) {
    if (ch < cl) {
        int remaining = ch;
        dx = (uint16_t)(dx >> remaining);
        int need = cl - remaining;
        dx = (uint16_t)((dx & 0x00FF) | (source[di] << 8));
        di++;
        ch = 8;
        cl = need;
    }
    dx = (uint16_t)(dx >> cl);
    ch -= cl;
}

// sub_7CF8 : contrôle, valeurs (sub_7C3F), puis filtre de prédiction (sub_797C) quand l'octet 7 n'est pas nul.
bool SpeechDecompressor::decodeBlock(const uint8_t *block, uint8_t *output) {
    uint16_t length = readWord(block);
    uint16_t check = 0;
    for (size_t k = 0; k < length / 2; k++) {
        check ^= readWord(block + 2 * k);
    }
    if (check != 0xACED) {
        printf("Speech: bloc invalide (controle %04X)\n", check);
        return false;
    }
    uint16_t samples = readWord(block + 2);
    int param = block[6];
    int order = block[7];
    std::vector<uint8_t> source(block, block + length);
    source.resize(length + 16, 0);
    std::vector<uint8_t> work(0x1770, 0);
    size_t table = (size_t)(param - 8) * 27;
    size_t src = 8 + 2 * order;
    uint16_t dx = readWord(source.data() + src);
    size_t di = src + 2;
    int ch = 8;
    size_t pos = order;
    for (uint16_t n = 0; n < samples; n++) {
        int rank = kCodeRank[dx & 0xFF];
        consumeBits(dx, ch, kCodeTables[table + rank], source, di);
        int cl = kCodeTables[table + rank + 9];
        uint8_t al = (uint8_t)(dx & 0xFF);
        int rotation = cl & 7;
        if (rotation != 0) {
            al = (uint8_t)((al >> rotation) | (al << (8 - rotation)));
        }
        uint16_t ax = al;
        if (al & 0x80) {
            ax |= 0xFF00;
        }
        ax ^= (uint16_t)(kCodeTables[table + rank + 18] << 8);
        ax = (uint16_t)(ax << cl);
        work[pos] = (uint8_t)((ax >> 8) ^ 0x80);
        pos++;
        consumeBits(dx, ch, cl, source, di);
    }
    if (order != 0) {
        for (uint16_t k = 0; k < samples; k++) {
            int32_t sum = 0;
            for (int j = 0; j < order; j++) {
                int8_t value = (int8_t)(work[k + j] ^ 0x80);
                int16_t coef = (int16_t)readWord(block + 8 + 2 * (order - 1 - j));
                sum += (int32_t)value * coef;
            }
            uint32_t bits = (uint32_t)sum;
            uint8_t delta = (uint8_t)((bits >> 12) + ((bits >> 11) & 1));
            work[k + order] = (uint8_t)(work[k + order] - delta);
        }
    }
    memcpy(output, work.data() + order, samples);
    return true;
}

// sub_1C574 : u32 taille décompressée, puis blocs (u16 longueur, u16 nombre d'échantillons).
uint8_t *SpeechDecompressor::Decompress(const uint8_t *compData, size_t compSize, size_t &uncompSize) {
    uncompSize = 0;
    if (compSize < 4) {
        return nullptr;
    }
    uint32_t total = (uint32_t)(compData[0] | (compData[1] << 8) | (compData[2] << 16) | (compData[3] << 24));
    uint8_t *output = new uint8_t[total];
    size_t pos = 4;
    size_t written = 0;
    while (written < total && pos + 10 <= compSize) {
        uint16_t length = readWord(compData + pos);
        uint16_t samples = readWord(compData + pos + 2);
        if (length == 0 || pos + length > compSize || written + samples > total) {
            break;
        }
        if (!this->decodeBlock(compData + pos, output + written)) {
            break;
        }
        written += samples;
        pos += length;
    }
    uncompSize = written;
    return output;
}
